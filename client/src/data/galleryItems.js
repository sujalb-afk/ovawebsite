export function getUniqueGalleryItems(items = GALLERY_ITEMS) {
  const deduped = Array.from(new Map(items.map((item) => [item.src, item])).values());
  return deduped
    .filter((item) => item.status !== 'draft')
    .sort((a, b) => new Date(b.publishedAt) - new Date(a.publishedAt));
}

